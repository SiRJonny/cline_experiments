/**
 * Build tool: writes every texture as a PNG, exports the mesh as OBJ + MTL and
 * dumps a small JSON summary of the model.
 *
 *   node budapest-bus/tools/build-assets.mjs [--out budapest-bus/assets]
 */

import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildTextures } from '../src/textures/index.js';
import { buildBus } from '../src/model/index.js';
import { encodeImage } from '../src/core/png.js';

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(here, '..');

const argv = process.argv.slice(2);
const outIndex = argv.indexOf('--out');
const outRoot = outIndex >= 0 ? resolve(argv[outIndex + 1]) : join(projectRoot, 'assets');

const textureDir = join(outRoot, 'textures');
const modelDir = join(outRoot, 'model');

function fmt(n, digits = 4) {
  return Number(n.toFixed(digits)).toString();
}

/** Minimal but complete OBJ writer (one group per mesh). */
function toOBJ(model) {
  const lines = [
    '# BKV city bus — procedural mesh',
    `# ${model.name}`,
    `# meshes: ${model.meshes.length}, triangles: ${model.stats.triangles}`,
    '# generated by budapest-bus/tools/build-assets.mjs — do not edit by hand',
    '',
    'mtllib bkv_bus.mtl',
    '',
  ];
  const v = [];
  const vt = [];
  const vn = [];
  for (const mesh of model.meshes) {
    const material = model.materials[mesh.material];
    lines.push(`o ${mesh.name}`);
    lines.push(`g ${mesh.name}`);
    lines.push(`usemtl ${material.name}`);
    const vBase = v.length + 1;
    const vtBase = vt.length + 1;
    const vnBase = vn.length + 1;
    for (let i = 0; i < mesh.positions.length; i += 3) {
      v.push(`v ${fmt(mesh.positions[i])} ${fmt(mesh.positions[i + 1])} ${fmt(mesh.positions[i + 2])}`);
    }
    for (let i = 0; i < mesh.uvs.length; i += 2) vt.push(`vt ${fmt(mesh.uvs[i], 5)} ${fmt(mesh.uvs[i + 1], 5)}`);
    for (let i = 0; i < mesh.normals.length; i += 3) {
      vn.push(`vn ${fmt(mesh.normals[i], 3)} ${fmt(mesh.normals[i + 1], 3)} ${fmt(mesh.normals[i + 2], 3)}`);
    }
    for (let i = 0; i < mesh.indices.length; i += 3) {
      const a = mesh.indices[i] + 1;
      const b = mesh.indices[i + 1] + 1;
      const c = mesh.indices[i + 2] + 1;
      lines.push(
        `f ${vBase + a - 1}/${vtBase + a - 1}/${vnBase + a - 1} ` +
        `${vBase + b - 1}/${vtBase + b - 1}/${vnBase + b - 1} ` +
        `${vBase + c - 1}/${vtBase + c - 1}/${vnBase + c - 1}`,
      );
    }
    lines.push('');
  }
  lines.push(...v, ...vt, ...vn, '');
  return lines.join('\n');
}

/** MTL writer: PBR-ish values are exported as classic Phong fields. */
function toMTL(model) {
  const lines = ['# BKV city bus — materials', `# ${model.materials.length} materials`, ''];
  for (const m of model.materials) {
    const kd = m.baseColor ?? [0.5, 0.5, 0.5];
    lines.push(`newmtl ${m.name}`);
    lines.push(`Kd ${fmt(kd[0], 4)} ${fmt(kd[1], 4)} ${fmt(kd[2], 4)}`);
    lines.push(`Ka ${fmt(kd[0] * 0.1, 4)} ${fmt(kd[1] * 0.1, 4)} ${fmt(kd[2] * 0.1, 4)}`);
    const spec = 1 - (m.roughness ?? 0.5);
    lines.push(`Ks ${fmt(spec, 3)} ${fmt(spec, 3)} ${fmt(spec, 3)}`);
    lines.push(`Ns ${fmt(Math.max(1, (1 - (m.roughness ?? 0.5)) * 400), 1)}`);
    lines.push(`d ${fmt(m.opacity ?? 1, 3)}`);
    if ((m.opacity ?? 1) < 1) lines.push('Tr 1');
    if (m.map) lines.push(`map_Kd textures/${m.map}.png`);
    if (m.emissiveMap) lines.push(`map_Ke textures/${m.emissiveMap}.png`);
    if (m.emissive && m.emissive.some((c) => c > 0.01)) {
      lines.push(`Ke ${fmt(m.emissive[0], 3)} ${fmt(m.emissive[1], 3)} ${fmt(m.emissive[2], 3)}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

function main() {
  const started = Date.now();
  rmSync(textureDir, { recursive: true, force: true });
  mkdirSync(textureDir, { recursive: true });
  mkdirSync(modelDir, { recursive: true });

  const textures = buildTextures();
  let bytes = 0;
  for (const [name, image] of Object.entries(textures)) {
    const png = encodeImage(image);
    writeFileSync(join(textureDir, `${name}.png`), png);
    bytes += png.length;
    console.log(`texture  ${name.padEnd(18)} ${image.width}x${image.height}  ${(png.length / 1024).toFixed(0)} KiB`);
  }

  const model = buildBus();
  writeFileSync(join(modelDir, 'bkv_bus.obj'), toOBJ(model));
  writeFileSync(join(modelDir, 'bkv_bus.mtl'), toMTL(model));
  writeFileSync(
    join(modelDir, 'model.json'),
    `${JSON.stringify(
      {
        name: model.name,
        units: 'metres',
        axes: { forward: '+X', up: '+Y', right: '+Z' },
        bounds: model.bounds,
        stats: model.stats,
        materials: model.materials,
        meshes: model.meshes.map((m) => ({
          name: m.name,
          material: model.materials[m.material].name,
          vertices: m.positions.length / 3,
          triangles: m.indices.length / 3,
        })),
      },
      null,
      2,
    )}\n`,
  );

  console.log('');
  console.log(`model    ${model.meshes.length} meshes, ${model.stats.triangles} triangles, ${model.materials.length} materials`);
  console.log(`bounds   ${model.bounds.min.map((n) => fmt(n, 2)).join(' / ')}  ..  ${model.bounds.max.map((n) => fmt(n, 2)).join(' / ')}`);
  console.log(`written  ${outRoot}`);
  console.log(`elapsed  ${((Date.now() - started) / 1000).toFixed(1)} s`);
}

main();
